/* Try to reuse the load buffer to conserve memory */
void *board_spl_fit_buffer_addr(ulong fit_size, int sectors, int bl_len)
{
	static void *buf;
	static size_t size;

	if (size < sectors * bl_len) {
		free(buf);
		size = sectors * bl_len;
		buf = malloc_cache_aligned(size);
	}
	return buf;
}

/* Local flags for spl_image; start from the "top" to avoid conflicts */
#define SPL_IMX_CONTAINER	0x80000000
#define SPL_COMPRESSED		0x40000000

int image_compression(enum spl_test_image type)
{
	switch (type) {
	case LEGACY_LZMA:
	case FIT_INTERNAL_LZMA:
	case FIT_EXTERNAL_LZMA:
		return IH_COMP_LZMA;
	case FIT_INTERNAL_ZSTD:
	case FIT_EXTERNAL_ZSTD:
		return IH_COMP_ZSTD;
	default:
		return IH_COMP_NONE;
	}
}

void generate_data(char *data, size_t size, const char *test_name)
{
	int i;
	unsigned int seed = 1;

	while (*test_name) {
		seed += *test_name++;
		rand_r(&seed);
	}

	for (i = 0; i < size; i++)
		data[i] = (i & 0xf) << 4 | (rand_r(&seed) & 0xf);
}

static size_t create_legacy(void *dst, struct spl_image_info *spl_image,
			    size_t *data_offset, int comp)
{
	struct legacy_img_hdr *hdr = dst;
	void *data = dst + sizeof(*hdr);

	if (data_offset)
		*data_offset = data - dst;

	if (!dst)
		goto out;

	image_set_magic(hdr, IH_MAGIC);
	image_set_time(hdr, 0);
	image_set_size(hdr, spl_image->size);
	image_set_load(hdr, spl_image->load_addr);
	image_set_ep(hdr, spl_image->entry_point);
	image_set_dcrc(hdr, crc32(0, data, spl_image->size));
	image_set_os(hdr, spl_image->os);
	image_set_arch(hdr, IH_ARCH_DEFAULT);
	image_set_type(hdr, IH_TYPE_FIRMWARE);
	image_set_comp(hdr, comp);
	image_set_name(hdr, spl_image->name);
	image_set_hcrc(hdr, crc32(0, (void *)hdr, sizeof(*hdr)));

out:
	return sizeof(*hdr) + spl_image->size;
}

static size_t create_imx8(void *dst, struct spl_image_info *spl_image,
			  size_t *data_offset)
{
	struct container_hdr *hdr = dst;
	struct boot_img_t *img = dst + sizeof(*hdr);
	size_t length = sizeof(*hdr) + sizeof(*img);
	/* Align to MMC block size for now */
	void *data = dst + 512;

	if (data_offset)
		*data_offset = data - dst;

	if (!dst)
		goto out;

	hdr->version = CONTAINER_HDR_VERSION;
	hdr->length_lsb = length & 0xff;
	hdr->length_msb = length >> 8;
	hdr->tag = CONTAINER_HDR_TAG;
	hdr->num_images = 1;

	/* spl_load_imx_container doesn't handle endianness; whoops! */
	img->offset = data - dst;
	img->size = spl_image->size;
	img->dst = spl_image->load_addr;
	img->entry = spl_image->entry_point;

out:
	return data - dst + spl_image->size;
}

#define ADDRESS_CELLS (sizeof(uintptr_t) / sizeof(u32))

static inline int fdt_property_addr(void *fdt, const char *name, uintptr_t val)
{
	if (sizeof(uintptr_t) == sizeof(u32))
		return fdt_property_u32(fdt, name, val);
	return fdt_property_u64(fdt, name, val);
}

static size_t start_fit(void *dst, size_t fit_size, size_t data_size,
			bool external)
{
	void *data;

	if (fdt_create(dst, fit_size))
		return 0;
	if (fdt_finish_reservemap(dst))
		return 0;
	if (fdt_begin_node(dst, ""))
		return 0;
	if (fdt_property_u32(dst, FIT_TIMESTAMP_PROP, 0))
		return 0;
	if (fdt_property_u32(dst, "#address-cells", ADDRESS_CELLS))
		return 0;
	if (fdt_property_string(dst, FIT_DESC_PROP, ""))
		return 0;

	if (fdt_begin_node(dst, "images"))
		return 0;
	if (fdt_begin_node(dst, "u-boot"))
		return 0;

	if (external) {
		if (fdt_property_u32(dst, FIT_DATA_OFFSET_PROP, 0))
			return 0;
		return fit_size;
	}

	if (fdt_property_placeholder(dst, FIT_DATA_PROP, data_size, &data))
		return 0;
	return data - dst;
}

static size_t create_fit(void *dst, struct spl_image_info *spl_image,
			 size_t *data_offset, bool external, int comp)
{
	/*
	 * What the FIT needs besides the payload: a fixed part, measured on
	 * 64-bit sandbox for the longest OS name used here, and the name, which
	 * goes in twice, as the description of both the image and the
	 * configuration. For external data this is also where the data starts,
	 * which the loader expects 4-byte aligned, as both terms are.
	 */
	size_t prop_size = 540 + 2 * ALIGN(strlen(spl_image->name) + 1, 4);
	size_t total_size = prop_size + spl_image->size;
	void *payload = NULL;
	size_t off, size;

	if (external) {
		size = prop_size;
		off = size;
	} else {
		char tmp[256];

		size = total_size;
		off = start_fit(tmp, sizeof(tmp), 0, false);
		if (!off)
			return 0;
	}

	if (data_offset)
		*data_offset = off;

	if (!dst)
		goto out;

	/*
	 * fdt_create() clears every byte of the buffer it is given. For
	 * internal data that buffer covers the payload our caller was asked to
	 * write beforehand, so keep a copy across the call. Nothing written
	 * after it reaches back that far.
	 */
	if (!external && spl_image->size) {
		payload = malloc(spl_image->size);
		if (!payload)
			return 0;
		memcpy(payload, dst + off, spl_image->size);
	}

	if (start_fit(dst, size, spl_image->size, external) != off) {
		free(payload);
		return 0;
	}

	if (payload) {
		memcpy(dst + off, payload, spl_image->size);
		free(payload);
	}

	if (fdt_property_string(dst, FIT_DESC_PROP, spl_image->name))
		return 0;
	if (fdt_property_string(dst, FIT_TYPE_PROP, "firmware"))
		return 0;
	if (fdt_property_string(dst, FIT_COMP_PROP,
				genimg_get_comp_short_name(comp)))
		return 0;
	if (fdt_property_u32(dst, FIT_DATA_SIZE_PROP, spl_image->size))
		return 0;
	if (fdt_property_string(dst, FIT_OS_PROP,
				genimg_get_os_short_name(spl_image->os)))
		return 0;
	if (fdt_property_string(dst, FIT_ARCH_PROP,
				genimg_get_arch_short_name(IH_ARCH_DEFAULT)))
		return 0;
	if (fdt_property_addr(dst, FIT_ENTRY_PROP, spl_image->entry_point))
		return 0;
	if (fdt_property_addr(dst, FIT_LOAD_PROP, spl_image->load_addr))
		return 0;
	if (fdt_end_node(dst)) /* u-boot */
		return 0;
	if (fdt_end_node(dst)) /* images */
		return 0;

	if (fdt_begin_node(dst, "configurations"))
		return 0;
	if (fdt_property_string(dst, FIT_DEFAULT_PROP, "config-1"))
		return 0;
	if (fdt_begin_node(dst, "config-1"))
		return 0;
	if (fdt_property_string(dst, FIT_DESC_PROP, spl_image->name))
		return 0;
	if (fdt_property_string(dst, FIT_FIRMWARE_PROP, "u-boot"))
		return 0;
	if (fdt_end_node(dst)) /* configurations */
		return 0;
	if (fdt_end_node(dst)) /* config-1 */
		return 0;

	if (fdt_end_node(dst)) /* root */
		return 0;
	if (fdt_finish(dst))
		return 0;

	if (external) {
		if (fdt_totalsize(dst) > size)
			return 0;
		fdt_set_totalsize(dst, size);
	}

out:
	return total_size;
}

size_t create_image(void *dst, enum spl_test_image type,
		    struct spl_image_info *info, size_t *data_offset)
{
	int comp = image_compression(type);
	bool external = false;

	info->os = IH_OS_U_BOOT;
	info->load_addr = CONFIG_TEXT_BASE;
	info->entry_point = CONFIG_TEXT_BASE + 0x100;
	info->flags = comp != IH_COMP_NONE ? SPL_COMPRESSED : 0;

	switch (type) {
	case LEGACY_LZMA:
	case LEGACY:
		return create_legacy(dst, info, data_offset, comp);
	case IMX8:
		info->flags = SPL_IMX_CONTAINER;
		return create_imx8(dst, info, data_offset);
	case FIT_EXTERNAL:
	case FIT_EXTERNAL_LZMA:
	case FIT_EXTERNAL_ZSTD:
		/*
		 * spl_fit_append_fdt will clobber external images with U-Boot's
		 * FDT if the image doesn't have one. Just set the OS to
		 * something which doesn't take a devicetree.
		 */
		if (!IS_ENABLED(CONFIG_LOAD_FIT_FULL))
			info->os = IH_OS_TEE;
		external = true;
	case FIT_INTERNAL:
	case FIT_INTERNAL_LZMA:
	case FIT_INTERNAL_ZSTD:
		info->flags |= SPL_FIT_FOUND;
		return create_fit(dst, info, data_offset, external, comp);
	}

	return 0;
}

int check_image_info(struct unit_test_state *uts, struct spl_image_info *info1,
		     struct spl_image_info *info2)
{
	if (info2->name) {
		if (info1->flags & SPL_FIT_FOUND)
			ut_asserteq_str(genimg_get_os_name(info1->os),
					info2->name);
		else
			ut_asserteq_str(info1->name, info2->name);
	}

	if (info1->flags & SPL_IMX_CONTAINER)
		ut_asserteq(IH_OS_INVALID, info2->os);
	else
		ut_asserteq(info1->os, info2->os);

	ut_asserteq(info1->entry_point, info2->entry_point);
	if (info1->flags & (SPL_FIT_FOUND | SPL_IMX_CONTAINER) ||
	    info2->flags & SPL_COPY_PAYLOAD_ONLY) {
		ut_asserteq(info1->load_addr, info2->load_addr);
		if (info1->flags & SPL_IMX_CONTAINER)
			ut_asserteq(0, info2->size);
		else if (!(info1->flags & SPL_COMPRESSED))
			ut_asserteq(info1->size, info2->size);
	} else {
		ut_asserteq(info1->load_addr - sizeof(struct legacy_img_hdr),
			    info2->load_addr);
		ut_asserteq(info1->size + sizeof(struct legacy_img_hdr),
			    info2->size);
	}

	return 0;
}

static ulong spl_test_read(struct spl_load_info *load, ulong sector,
			   ulong count, void *buf)
{
	memcpy(buf, load->priv + sector, count);
	return count;
}

static int spl_test_image(struct unit_test_state *uts, const char *test_name,
			  enum spl_test_image type)
{
	size_t img_size, img_data, data_size = SPL_TEST_DATA_SIZE;
	struct spl_image_info info_write = {
		.name = test_name,
		.size = data_size,
	}, info_read = { };
	char plain[SPL_TEST_DATA_SIZE];
	char *data;
	void *img;

	img_size = create_image(NULL, type, &info_write, &img_data);
	ut_assert(img_size);
	img = calloc(img_size, 1);
	ut_assertnonnull(img);

	data = img + img_data;
	generate_data(plain, data_size, test_name);
	memcpy(data, plain, data_size);
	ut_asserteq(img_size, create_image(img, type, &info_write, NULL));
	/* Compare against a copy, so that losing the payload can't go unseen */
	ut_asserteq_mem(plain, data, data_size);

	if (type == LEGACY) {
		ut_assertok(spl_parse_image_header(&info_read, NULL, img));
		if (check_image_info(uts, &info_write, &info_read))
			return CMD_RET_FAILURE;
	} else {
		struct spl_load_info load;

		spl_load_init(&load, spl_test_read, img, 1);
		if (type == IMX8)
			ut_assertok(spl_load_imx_container(&info_read, &load,
							   0));
		else if (IS_ENABLED(CONFIG_SPL_FIT_FULL))
			ut_assertok(spl_parse_image_header(&info_read, NULL,
							   img));
		else
			ut_assertok(spl_load_simple_fit(&info_read, &load, 0,
							img));
		if (check_image_info(uts, &info_write, &info_read))
			return CMD_RET_FAILURE;
		ut_asserteq_mem(plain, phys_to_virt(info_write.load_addr),
				data_size);
	}

	free(img);
	return 0;
}
SPL_IMG_TEST(spl_test_image, LEGACY, 0);
SPL_IMG_TEST(spl_test_image, IMX8, 0);
SPL_IMG_TEST(spl_test_image, FIT_INTERNAL, 0);
SPL_IMG_TEST(spl_test_image, FIT_EXTERNAL, 0);

/*
 * Build a FIT with external data, overwrite one property of the image node
 * with a hostile value and check that loading fails with the expected error.
 * The external-data properties are excluded from the configuration signature,
 * so load_simple_fit() must reject values that would wrap its offset/size
 * arithmetic rather than read from a bogus location.
 */
static int check_fit_ext_prop(struct unit_test_state *uts, const char *prop,
			      u32 value, uint bl_len, spl_load_reader h_read,
			      ulong fit_offset, int expected)
{
	size_t img_size, img_data, data_size = SPL_TEST_DATA_SIZE;
	struct spl_image_info info_write = {
		.name = "ext-prop",
		.size = data_size,
	}, info_read = { };
	struct spl_load_info load;
	void *img;
	int node;

	img_size = create_image(NULL, FIT_EXTERNAL, &info_write, &img_data);
	ut_assert(img_size);
	img = calloc(img_size, 1);
	ut_assertnonnull(img);

	generate_data(img + img_data, data_size, "ext-prop");
	ut_asserteq(img_size, create_image(img, FIT_EXTERNAL, &info_write,
					   NULL));

	node = fdt_path_offset(img, FIT_IMAGES_PATH);
	ut_assert(node >= 0);
	node = fdt_first_subnode(img, node);
	ut_assert(node >= 0);
	ut_assertok(fdt_setprop_inplace_u32(img, node, prop, value));

	spl_load_init(&load, h_read, img, bl_len);
	ut_asserteq(expected,
		    spl_load_simple_fit(&info_read, &load, fit_offset, img));

	free(img);
	return 0;
}

/*
 * A FIT image's data-size property is not covered by the configuration
 * signature, so it is untrusted input. load_simple_fit() must reject a
 * data-size larger than the destination rather than overrun it, because the
 * device read happens before the image hash is verified.
 */
static int spl_test_fit_external_oversize(struct unit_test_state *uts)
{
	if (!image_supported(FIT_EXTERNAL))
		return -EAGAIN;

	return check_fit_ext_prop(uts, FIT_DATA_SIZE_PROP, 0x40000000, 1,
				  spl_test_read, 0, -EFBIG);
}
SPL_TEST(spl_test_fit_external_oversize, 0);

/*
 * A data-offset which wraps past UINT32_MAX once the external-data base
 * offset is added must be rejected before it is used as a read offset.
 */
static int spl_test_fit_data_offset_overflow(struct unit_test_state *uts)
{
	if (!image_supported(FIT_EXTERNAL))
		return -EAGAIN;

	return check_fit_ext_prop(uts, FIT_DATA_OFFSET_PROP, 0xffffffff, 1,
				  spl_test_read, 0, -EINVAL);
}
SPL_TEST(spl_test_fit_data_offset_overflow, 0);

/*
 * A data-size whose block-aligned read size wraps past ULONG_MAX must be
 * rejected. Since data-size is a 32-bit property, the wrap is only reachable
 * when ulong is 32 bits wide, so skip the test on other targets.
 */
static int spl_test_fit_data_size_overflow(struct unit_test_state *uts)
{
	if (!image_supported(FIT_EXTERNAL) || sizeof(ulong) != 4)
		return -EAGAIN;

	return check_fit_ext_prop(uts, FIT_DATA_SIZE_PROP, 0xffffffff, 2,
				  spl_test_read, 0, -EOVERFLOW);
}
SPL_TEST(spl_test_fit_data_size_overflow, 0);

/* Device offset the reader pretends the FIT was loaded from */
static ulong spl_test_fit_offset;

static ulong spl_test_read_fit_offset(struct spl_load_info *load, ulong sector,
				      ulong count, void *buf)
{
	return spl_test_read(load, sector - spl_test_fit_offset, count, buf);
}

/*
 * An aligned external-data offset which wraps past ULONG_MAX once the FIT's
 * offset on the device is added must be rejected before it is used as a read
 * offset.
 */
static int spl_test_fit_read_offset_overflow(struct unit_test_state *uts)
{
	if (!image_supported(FIT_EXTERNAL))
		return -EAGAIN;

	/* So that ULONG_MAX - fit_offset < the aligned external-data offset */
	spl_test_fit_offset = ULONG_MAX - 0xfff;

	return check_fit_ext_prop(uts, FIT_DATA_OFFSET_PROP, 0x1000, 1,
				  spl_test_read_fit_offset, spl_test_fit_offset,
				  -EINVAL);
}
SPL_TEST(spl_test_fit_read_offset_overflow, 0);

/*
 * A read whose end position (read_offset + size) wraps past the addressable
 * range must be rejected.
 */
static int spl_test_fit_read_end_overflow(struct unit_test_state *uts)
{
	if (!image_supported(FIT_EXTERNAL))
		return -EAGAIN;

	/*
	 * The aligned external-data offset (0x2000 plus the size of the FIT
	 * itself) stays below the 0x2fff bytes remaining before ULONG_MAX, so
	 * read_offset passes the offset-wrap check above, but reading the
	 * SPL_TEST_DATA_SIZE bytes of data crosses past UINTPTR_MAX.
	 */
	spl_test_fit_offset = ULONG_MAX - 0x2fff;

	return check_fit_ext_prop(uts, FIT_DATA_OFFSET_PROP, 0x2000, 1,
				  spl_test_read_fit_offset, spl_test_fit_offset,
				  -EINVAL);
}
SPL_TEST(spl_test_fit_read_end_overflow, 0);

