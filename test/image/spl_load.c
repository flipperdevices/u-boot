const size_t zstd_compressed_size = sizeof(zstd_compressed);

/**
 * canned_blob() - Look up the canned compressed payload for a compression
 * @comp: IH_COMP_... as returned by image_compression()
 * @size: Set to the size of the returned blob
 *
 * Each canned blob holds what generate_data() produces for a seed equal to
 * the short name of its compression.
 *
 * Return: the blob
 */
static const char *canned_blob(int comp, size_t *size)
{
	switch (comp) {
	case IH_COMP_ZSTD:
		*size = zstd_compressed_size;
		return zstd_compressed;
	default:
		*size = lzma_compressed_size;
		return lzma_compressed;
	}
}

int do_spl_test_load(struct unit_test_state *uts, const char *test_name,
		     enum spl_test_image type, struct spl_image_loader *loader,
		     int (*write_image)(struct unit_test_state *, void *, size_t))
{
	size_t img_size, img_data, plain_size = SPL_TEST_DATA_SIZE;
	struct spl_image_info info_write = { .name = test_name };
	struct spl_image_info info_read = { };
	struct spl_boot_device bootdev = {
		.boot_device = loader->boot_device,
	};
	int comp = image_compression(type);
	char plain[SPL_TEST_DATA_SIZE];
	const char *blob = NULL;
	const char *payload;
	size_t blob_size = 0;
	char *data;
	void *img;

	if (comp != IH_COMP_NONE)
		blob = canned_blob(comp, &blob_size);
	info_write.size = blob ? blob_size : plain_size;

	img_size = create_image(NULL, type, &info_write, &img_data);
	ut_assert(img_size);
	img = calloc(img_size, 1);
	ut_assertnonnull(img);

	data = img + img_data;
	if (blob) {
		/* The canned blob holds what this seed generates */
		generate_data(plain, plain_size,
			      genimg_get_comp_short_name(comp));
		payload = blob;
	} else {
		generate_data(plain, plain_size, test_name);
		payload = plain;
	}
	memcpy(data, payload, info_write.size);
	ut_asserteq(img_size, create_image(img, type, &info_write, NULL));
	/* Compare against a copy, so that losing the payload can't go unseen */
	ut_asserteq_mem(payload, data, info_write.size);

	if (write_image(uts, img, img_size))
		return CMD_RET_FAILURE;

	ut_assertok(loader->load_image(&info_read, &bootdev));
	if (check_image_info(uts, &info_write, &info_read))
		return CMD_RET_FAILURE;
	if (blob)
		ut_asserteq(plain_size, info_read.size);
	ut_asserteq_mem(plain, phys_to_virt(info_write.load_addr), plain_size);

	free(img);
	return 0;
}
